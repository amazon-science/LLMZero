import logging

from ..prompts import ExecutionCoderPrompt
from .base_agent import BaseAgent
from .utils import init_llm

logger = logging.getLogger(__name__)


class ExecutionCoderAgent(BaseAgent):
    """
    Generate environment-specific execution scripts that wrap entry point scripts.

    This agent focuses on generating the execution wrapper that handles:
    - Ray job submission commands
    - Environment configuration
    - Resource allocation
    - Execution context setup

    The generated script wraps the entry point script generated by PostTrainingCoderAgent.

    Agent Input:
    - Entry point script path
    - Execution environment configuration (Ray cluster address, etc.)
    - Resource requirements

    Agent Output:
    - Execution script (e.g., Ray job submission wrapper)
    """

    def __init__(self, config, manager, llm_config, prompt_template):
        super().__init__(config=config, manager=manager)

        self.coder_llm_config = llm_config
        self.coder_prompt_template = prompt_template

        self.coder_prompt = ExecutionCoderPrompt(
            llm_config=self.coder_llm_config,
            manager=self.manager,
            template=self.coder_prompt_template,
        )

        if self.coder_llm_config.multi_turn:
            self.coder_llm = init_llm(
                llm_config=self.coder_llm_config,
                agent_name="execution_coder",
                multi_turn=self.coder_llm_config.multi_turn,
            )

    def __call__(self):
        self.manager.log_agent_start(
            "ExecutionCoderAgent: starting to build and send execution script generation prompt to the LLM."
        )

        # Build prompt for generating execution wrapper script
        prompt = self.coder_prompt.build()

        if not self.coder_llm_config.multi_turn:
            self.coder_llm = init_llm(
                llm_config=self.coder_llm_config,
                agent_name="execution_coder",
                multi_turn=self.coder_llm_config.multi_turn,
            )

        response = self.coder_llm.assistant_chat(prompt)

        generated_script = self.coder_prompt.parse(response)

        self.manager.log_agent_end(
            "ExecutionCoderAgent: execution script generation prompt handled and code parsed from response."
        )

        return generated_script
